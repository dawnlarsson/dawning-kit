#!/usr/bin/env python3
"""
The timezone table in src/lib.util.c, written from tzdata.

    python3 src/build/zones.py [ZONEINFO]      (default /usr/share/zoneinfo)

Rewrites the text between the "zones: generated" and "zones: end" lines of
src/lib.util.c. Needs a tzdata install with zone.tab, zone1970.tab,
tzdata.zi and TZif v2+ files, and node with full ICU for the spoken names.

What it writes:

  clock_zones     every name in zone.tab or zone1970.tab, plus UTC and GMT,
                  with the POSIX rule from its TZif footer (the rule that
                  governs every time after the file's last transition) and
                  the name ICU's English generic long form gives it.
  clock_zone_links  every other tzdata name (backward links, Etc/UTC, ...)
                  whose target is in clock_zones, pointing at that entry.
  clock_zone_codes  ISO 3166 country code to the zone most of its people
                  live in: the only zone.tab row for a one-zone country, and
                  the choice in MOST_PEOPLE for every country with several.

All three are sorted by lower-case name so lookups can bisect, and the
generator refuses a country with several zones and no choice, an empty
footer, and any spoken name that is not plain ASCII after folding.
"""

import os
import re
import subprocess
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "lib.util.c")
BEGIN = "/* ---- zones: generated by src/build/zones.py"
END = "/* ---- zones: end ---- */"

# Countries with more than one zone in zone.tab: the zone most of the
# country's people live in (the capital's where that is also the largest).
MOST_PEOPLE = {
    "AQ": "Antarctica/McMurdo",
    "AR": "America/Argentina/Buenos_Aires",
    "AU": "Australia/Sydney",
    "BR": "America/Sao_Paulo",
    "CA": "America/Toronto",
    "CD": "Africa/Kinshasa",
    "CL": "America/Santiago",
    "CN": "Asia/Shanghai",
    "CY": "Asia/Nicosia",
    "DE": "Europe/Berlin",
    "EC": "America/Guayaquil",
    "ES": "Europe/Madrid",
    "FM": "Pacific/Chuuk",
    "GL": "America/Nuuk",
    "ID": "Asia/Jakarta",
    "KI": "Pacific/Tarawa",
    "KZ": "Asia/Almaty",
    "MH": "Pacific/Majuro",
    "MN": "Asia/Ulaanbaatar",
    "MX": "America/Mexico_City",
    "MY": "Asia/Kuala_Lumpur",
    "NZ": "Pacific/Auckland",
    "PF": "Pacific/Tahiti",
    "PG": "Pacific/Port_Moresby",
    "PS": "Asia/Hebron",
    "PT": "Europe/Lisbon",
    "RU": "Europe/Moscow",
    "UA": "Europe/Kyiv",
    "UM": "Pacific/Midway",
    "US": "America/New_York",
    "UZ": "Asia/Tashkent",
}

EXTRA = ["UTC", "GMT"]


def c_string(text):
    assert all(32 <= ord(ch) < 127 for ch in text), text
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def footer(zoneinfo, name):
    with open(os.path.join(zoneinfo, name), "rb") as f:
        data = f.read()
    assert data[:4] == b"TZif" and data[4:5] in (b"2", b"3", b"4"), name
    rule = data.rstrip(b"\n").rsplit(b"\n", 1)[1].decode("ascii")
    assert rule and "\n" not in rule, name
    return rule


def spoken(names):
    script = r"""
const names = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const out = {};
for (const n of names) {
  const f = new Intl.DateTimeFormat('en-US', {timeZone: n, timeZoneName: 'longGeneric'});
  out[n] = f.formatToParts(new Date(Date.UTC(2026, 0, 15))).find(p => p.type == 'timeZoneName').value;
}
process.stdout.write(JSON.stringify(out));
"""
    import json
    got = subprocess.run(["node", "-e", script], input=json.dumps(names),
                         capture_output=True, text=True, check=True).stdout
    table = json.loads(got)
    folded = {}
    for name, word in table.items():
        word = unicodedata.normalize("NFKD", word)
        word = "".join(ch for ch in word if not unicodedata.combining(ch))
        word = word.replace("\u2019", "'").replace("\u2013", "-")
        if name in ("UTC", "GMT"):
            word = {"UTC": "Coordinated Universal Time",
                    "GMT": "Greenwich Mean Time"}[name]
        # ICU says "GMT+03:00" where it has no name; say nothing then.
        if re.match(r"^GMT[+-]", word):
            word = ""
        assert all(32 <= ord(ch) < 127 for ch in word), (name, word)
        folded[name] = word
    return folded


def main():
    zoneinfo = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    with open(os.path.join(zoneinfo, "tzdata.zi")) as f:
        zi = f.read().splitlines()
    version = zi[0].split()[-1]
    assert zi[0].startswith("# version"), zi[0]

    rows = {}
    for tab in ("zone.tab", "zone1970.tab"):
        with open(os.path.join(zoneinfo, tab)) as f:
            for line in f:
                if line.startswith("#") or not line.strip():
                    continue
                codes, _, name = line.rstrip("\n").split("\t")[:3]
                if tab == "zone.tab":
                    rows.setdefault(codes, []).append(name)
                rows.setdefault("names", [])
                rows["names"].append(name)
    names = sorted(set(rows.pop("names") + EXTRA), key=str.lower)

    links = {}
    for line in zi:
        if line.startswith("L "):
            _, target, alias = line.split()
            links[alias] = target

    def resolve(name):
        seen = 0
        while name not in names and name in links and seen < 8:
            name = links[name]
            seen += 1
        return name if name in names else None

    alias = {}
    for name in links:
        if name in names or name.startswith("posix") or name.startswith("right"):
            continue
        target = resolve(name)
        if target:
            alias[name] = target

    codes = {}
    for code, zones in rows.items():
        if len(zones) == 1:
            codes[code] = zones[0]
            continue
        assert code in MOST_PEOPLE, ("choose a zone for", code, zones)
        assert MOST_PEOPLE[code] in zones, (code, MOST_PEOPLE[code])
        codes[code] = MOST_PEOPLE[code]
    assert not set(MOST_PEOPLE) - set(codes), set(MOST_PEOPLE) - set(codes)

    rule = {name: footer(zoneinfo, name) for name in names}
    word = spoken(names)

    out = []
    out.append("%s from tzdata %s; ---- */" % (BEGIN, version))
    out.append("")
    out.append("#define CLOCK_ZONE_TZDATA \"%s\"" % version)
    out.append("")
    out.append("static const struct")
    out.append("{")
    out.append("        const char address_to name;")
    out.append("        const char address_to posix;")
    out.append("        const char address_to spoken;")
    out.append("} clock_zones[] = {")
    for name in names:
        out.append("        {%s, %s, %s}," % (c_string(name), c_string(rule[name]),
                                              c_string(word[name])))
    out.append("};")
    out.append("")
    out.append("static const struct")
    out.append("{")
    out.append("        const char address_to name;")
    out.append("        const char address_to zone;")
    out.append("} clock_zone_links[] = {")
    for name in sorted(alias, key=str.lower):
        out.append("        {%s, %s}," % (c_string(name), c_string(alias[name])))
    out.append("};")
    out.append("")
    out.append("static const struct")
    out.append("{")
    out.append("        char code[4];")
    out.append("        const char address_to zone;")
    out.append("} clock_zone_codes[] = {")
    for code in sorted(codes, key=str.lower):
        out.append("        {%s, %s}," % (c_string(code.lower()), c_string(codes[code])))
    out.append("};")
    out.append("")
    out.append(END)

    with open(TARGET) as f:
        text = f.read()
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    text = text[:start] + "\n".join(out) + text[stop:]
    with open(TARGET, "w") as f:
        f.write(text)

    longest = max(len(r) for r in rule.values())
    print("zones: tzdata %s, %d zones, %d links, %d countries, %d rules "
          "(longest %d), %d without a spoken name" %
          (version, len(names), len(alias), len(codes), len(set(rule.values())),
           longest, sum(1 for w in word.values() if not w)))


main()
